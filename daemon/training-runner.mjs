import { promises as fs } from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import crypto from 'node:crypto';

export const PRESETS = Object.freeze({
  '0.5b': { label: '0.5B QLoRA on 6GB', r: 16, lora_alpha: 16, target_modules: ['q_proj', 'k_proj', 'v_proj', 'o_proj'], learning_rate: 0.0002, epochs: 3, per_device_batch: 2, gradient_accumulation: 8, max_seq_len: 2048, fp16: true, bf16: false },
  '1.5b': { label: '1.5B QLoRA on 6GB', r: 8, lora_alpha: 8, target_modules: ['q_proj', 'v_proj'], learning_rate: 0.0002, epochs: 2, per_device_batch: 1, gradient_accumulation: 16, max_seq_len: 1024, fp16: true, bf16: false }
});

const OOM_LADDER = [
  'halve per-device batch size',
  'double gradient accumulation steps',
  'reduce max sequence length by half',
  'drop to the smaller preset (0.5B)'
];

const SCRIPT_TEMPLATE = `# AUTO-GENERATED by AIDE training-runner - pinned hyperparameters, edit nothing to reproduce
import json, math, os, sys
from pathlib import Path

DATASET = Path(r"{{DATASET}}")
OUTPUT = Path(r"{{OUTPUT}}")
P = {{PRESET}}

def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    rows = [json.loads(line) for line in DATASET.read_text(encoding="utf-8").splitlines() if line.strip()]
    samples = []
    for row in rows:
        text = row.get("text")
        prompt = f"{row.get('input')}\\n{row.get('output')}" if "input" in row else text
        if isinstance(prompt, str) and prompt.strip():
            samples.append(prompt.strip())
    if not samples:
        sys.exit("no usable samples in dataset")
    try:
        import torch
        from transformers import AutoModelForCausalLM, AutoTokenizer, Trainer, TrainingArguments, DataCollatorForLanguageModeling
        from peft import LoraConfig, get_peft_model
        from datasets import Dataset
    except Exception as error:
        sys.exit(f"training dependencies missing: {error}")

    dtype = torch.float16 if P["fp16"] else torch.bfloat16
    tokenizer = AutoTokenizer.from_pretrained(os.environ.get("AIDE_BASE_MODEL", ""), trust_remote_code=True)
    model = AutoModelForCausalLM.from_pretrained(os.environ.get("AIDE_BASE_MODEL", ""), torch_dtype=dtype, device_map="cuda", trust_remote_code=True)
    model = get_peft_model(model, LoraConfig(
        r=P["r"], lora_alpha=P["lora_alpha"], lora_dropout=0.05,
        target_modules=P["target_modules"], task_type="CAUSAL_LM"))
    encoded = Dataset.from_dict({"text": samples}).map(lambda row: tokenizer(row["text"], truncation=True, max_length=P["max_seq_len"]), batched=False)
    args = TrainingArguments(
        output_dir=str(OUTPUT / "checkpoints"), num_train_epochs=P["epochs"],
        per_device_train_batch_size=P["per_device_batch"],
        gradient_accumulation_steps=P["gradient_accumulation"],
        learning_rate=P["learning_rate"], fp16=P["fp16"], bf16=P["bf16"],
        logging_steps=5, save_total_limit=3, save_strategy="epoch",
        report_to=[], seed=42)
    trainer = Trainer(model=model, args=args, train_dataset=encoded,
                      data_collator=DataCollatorForLanguageModeling(tokenizer, mlm=False))
    trainer.train()
    trainer.save_model(str(OUTPUT / "adapter"))

if __name__ == "__main__":
    main()
`;

export class TrainingRunner {
  constructor({ workDir, pythonPath = process.env.AIDE_PYTHON || '', spawnChild = spawn, onEvent = null }) {
    this.workDir = workDir;
    this.pythonPath = pythonPath;
    this.spawnChild = spawnChild;
    this.onEvent = onEvent;
    this.job = null;
    this.child = null;
  }

  static jobId() {
    return `job-${crypto.randomBytes(4).toString('hex')}`;
  }

  status() {
    return this.job ? { ...this.job, oom_advice: this.job.oom ? OOM_LADDER : [] } : { state: 'idle' };
  }

  #publish(event, body) {
    try {
      this.onEvent?.('training', { event, ...body });
    } catch {
      this.lastEventError = true;
    }
  }

  async start({ datasetId, datasetPath, sampleCount, preset = '0.5b', approved = false }) {
    if (approved !== true) return { error: 'FORBIDDEN', message: 'training must be explicitly approved' };
    if (!PRESETS[preset]) return { error: 'BAD_REQUEST', message: `unknown preset: ${preset}` };
    if (!sampleCount || sampleCount < 10) return { error: 'BAD_REQUEST', message: `dataset needs >= 10 accepted samples (has ${sampleCount ?? 0})` };
    if (this.job && ['preparing', 'training'].includes(this.job.state)) return { error: 'CONFLICT', message: 'a training job is already running' };

    const id = TrainingRunner.jobId();
    const outputDir = path.join(this.workDir, id);
    const scriptPath = path.join(outputDir, 'train_sft.py');
    await fs.mkdir(outputDir, { recursive: true });
    await fs.writeFile(scriptPath, SCRIPT_TEMPLATE.replace('{{DATASET}}', datasetPath).replace('{{OUTPUT}}', outputDir).replace('{{PRESET}}', JSON.stringify(PRESETS[preset])), 'utf8');

    this.job = {
      id, preset, dataset_id: datasetId, sample_count: sampleCount, state: 'training',
      started_at: new Date().toISOString(), ended_at: null, exit_code: null,
      loss_last: null, loss_history: [], oom: false, error: null, output_dir: outputDir, script: scriptPath
    };
    this.#publish('started', { id, preset });

    const interp = this.pythonPath || 'python';
    const child = this.spawnChild(interp, [scriptPath], {
      cwd: outputDir,
      env: { ...process.env, PYTHONUNBUFFERED: '1' },
      stdio: ['ignore', 'pipe', 'pipe']
    });
    this.child = child;

    let stdoutBuffer = '';
    child.stdout?.setEncoding('utf8');
    child.stdout?.on('data', chunk => {
      stdoutBuffer += chunk;
      const lines = stdoutBuffer.split(/\r?\n/);
      stdoutBuffer = lines.pop() ?? '';
      for (const line of lines) this.#consumeLine(line);
    });
    let stderrTail = [];
    child.stderr?.setEncoding('utf8');
    child.stderr?.on('data', chunk => {
      for (const line of String(chunk).split(/\r?\n/)) {
        if (/out of memory|OutOfMemoryError/i.test(line)) this.#markOom();
      }
      stderrTail = [...stderrTail, ...String(chunk).split(/\r?\n/)].slice(-20);
    });
    const finish = code => {
      if (!this.job || this.job.id !== id) return;
      this.job.exit_code = code;
      this.job.state = code === 0 ? 'done' : 'error';
      this.job.ended_at = new Date().toISOString();
      if (code !== 0 && !this.job.error) this.job.error = stderrTail.filter(Boolean).join(' | ').slice(-1000) || `trainer exited with code ${code}`;
      this.#publish(this.job.state === 'done' ? 'completed' : 'failed', { id, exit_code: code });
      this.child = null;
    };
    child.once('error', error => {
      if (this.job && this.job.id === id) this.job.error = String(error.message || error);
      finish(-1);
    });
    child.once('exit', code => finish(code));
    return this.status();
  }

  #consumeLine(line) {
    const match = line.match(/loss["']?\]?\s*[=:]\s*([0-9.]+)/i);
    if (!match) return;
    const loss = Number.parseFloat(match[1]);
    if (!Number.isFinite(loss)) return;
    this.job.loss_last = loss;
    this.job.loss_history = [...this.job.loss_history, { at: Date.now(), loss }].slice(-500);
    this.#publish('loss', { id: this.job.id, loss });
  }

  #markOom() {
    if (this.job && !this.job.oom) {
      this.job.oom = true;
      this.#publish('oom-advice', { id: this.job.id, advice: OOM_LADDER });
    }
  }

  stop() {
    if (!this.child || !this.job) return { stopped: false, reason: 'nothing is running' };
    this.job.state = 'error';
    this.job.error = 'stopped by operator';
    this.child.kill();
    this.child = null;
    return { stopped: true };
  }

  async checkpoints(jobId = null) {
    const target = jobId ?? this.job?.id;
    if (!target) return [];
    const dir = path.join(this.workDir, target, 'checkpoints');
    const entries = await fs.readdir(dir).catch(() => []);
    const scored = [];
    for (const name of entries) {
      const metaPath = path.join(dir, name, 'trainer_state.json');
      try {
        const state = JSON.parse(await fs.readFile(metaPath, 'utf8'));
        const losses = (state.log_history ?? []).filter(entry => typeof entry.eval_loss === 'number');
        const best = losses.length > 0 ? Math.min(...losses.map(entry => entry.eval_loss)) : null;
        scored.push({ name, best_eval_loss: best });
      } catch {
        scored.push({ name, best_eval_loss: null });
      }
    }
    return scored.sort((a, b) => (a.best_eval_loss ?? Infinity) - (b.best_eval_loss ?? Infinity)).slice(0, 3);
  }
}

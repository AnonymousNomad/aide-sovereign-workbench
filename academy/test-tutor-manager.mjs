import assert from 'node:assert/strict';
import { mkdtemp, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { TutorManager } from './tutor-manager.mjs';

const root = await mkdtemp(path.join(tmpdir(), 'aide-tutor-'));
const tutor = new TutorManager({ coursesDir: path.join(process.cwd(), 'academy/courses'), progressPath: path.join(root, 'progress.json') });
await tutor.load();
assert.equal(tutor.catalog().length, 3);
assert.equal(tutor.session('python-foundations').lesson.id, 'variables');
const session = await tutor.complete('python-foundations', 'variables', 'I can name a value.');
assert.equal(session.lesson.id, 'control-flow');
assert.match(await readFile(path.join(root, 'progress.json'), 'utf8'), /variables/);
await tutor.complete('python-foundations', 'functions');
await tutor.complete('python-foundations', 'collections');
await tutor.complete('python-foundations', 'testing');
await tutor.complete('python-foundations', 'control-flow');
await tutor.complete('python-foundations', 'modules');
await tutor.complete('python-foundations', 'errors');
await tutor.complete('python-foundations', 'files');
await tutor.complete('python-foundations', 'debugging');
await tutor.complete('python-foundations', 'packaging');
await tutor.complete('python-foundations', 'capstone');
assert.equal(tutor.certificate('python-foundations').credential.credentialSubject.lessons_completed, 11);
console.log('tutor manager test passed');
